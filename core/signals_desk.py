"""
core/signals_desk.py - Quantitative Signals Desk evaluating 3 Mathematical Swing Strategies.

Implements:
1. Strategy 1: Breakout Momentum
   - 20-day high channel breakout
   - RVOL >= 1.3x (Relative Volume)
   - MACD expansion (MACD > Signal Line and positive/expanding histogram)
2. Strategy 2: Mean-Reversion Dips
   - High-ROIC quality pullbacks (ROIC >= 12%) to 50/200 EMA or Lower Bollinger Band
   - RSI <= 38 turning up (RSI <= 38 and RSI_t > RSI_{t-1})
3. Strategy 3: Multi-Factor Composite Swings
   - Trend alignment (EMA 50 > EMA 200, Price > EMA 50)
   - RVOL confirmation (RVOL >= 1.1x)
   - RSI momentum sweet-spot (40 <= RSI <= 68)
   - ATR-calibrated stop loss and target with R:R >= 2.0:1

Provides:
- scan_signals(symbols: List[str]) -> List[SignalCandidate]
- format_signals_card(candidates: Optional[List[SignalCandidate]]) -> str
"""

from __future__ import annotations
import logging
import math
from dataclasses import dataclass, field
from datetime import datetime, timezone
from typing import Dict, List, Optional, Any, Tuple

from feeds.base_feed import BaseFeed
from core.state_manager import StateManager

logger = logging.getLogger(__name__)


@dataclass
class SignalCandidate:
    """Represents a qualified swing trade candidate generated by a mathematical strategy."""
    symbol: str
    strategy_name: str
    entry_price: float
    stop_loss: float
    target_price: float
    rr_ratio: float
    metrics: Dict[str, Any] = field(default_factory=dict)
    timestamp: datetime = field(default_factory=lambda: datetime.now(timezone.utc))
    notes: Optional[str] = None
    passed: bool = True

    def to_dict(self) -> Dict[str, Any]:
        return {
            "symbol": self.symbol,
            "strategy_name": self.strategy_name,
            "entry_price": self.entry_price,
            "stop_loss": self.stop_loss,
            "target_price": self.target_price,
            "rr_ratio": self.rr_ratio,
            "metrics": self.metrics,
            "timestamp": self.timestamp.isoformat(),
            "notes": self.notes,
            "passed": self.passed,
        }


class SignalsDesk:
    """
    Quantitative Signals Desk evaluating market setups using strict mathematical rules.
    """

    # Quantitative Strategy Thresholds
    MOMENTUM_RVOL_MIN = 1.30          # Breakout relative volume >= 1.3x
    MOMENTUM_CHANNEL_DAYS = 20        # 20-day high channel
    DIP_ROIC_MIN = 0.12               # High-ROIC quality threshold (>= 12%)
    DIP_RSI_MAX = 38.0                # Oversold RSI threshold (<= 38)
    COMPOSITE_RVOL_MIN = 1.10         # Multi-factor RVOL threshold
    COMPOSITE_RSI_MIN = 40.0          # Multi-factor healthy RSI lower bound
    COMPOSITE_RSI_MAX = 70.0          # Multi-factor healthy RSI upper bound (not overbought)
    MIN_RR_RATIO = 2.00               # Risk-to-Reward hurdle >= 2.0:1

    def __init__(
        self,
        feed: Optional[BaseFeed] = None,
        state_mgr: Optional[StateManager] = None
    ):
        self.feed = feed
        self.state_mgr = state_mgr
        self._history_cache: Dict[str, Dict[str, List[float]]] = {}

    # -------------------------------------------------------------------------
    # Mathematical Indicator Engines
    # -------------------------------------------------------------------------

    @staticmethod
    def calculate_ema(series: List[float], period: int) -> List[float]:
        """Calculates Exponential Moving Average (EMA) for a series."""
        n = len(series)
        if n < period or period <= 0:
            return []
        
        # Initial SMA
        sma = sum(series[:period]) / period
        ema_values = [sma]
        multiplier = 2.0 / (period + 1)

        for i in range(period, n):
            val = series[i]
            ema_t = (val - ema_values[-1]) * multiplier + ema_values[-1]
            ema_values.append(ema_t)

        return ema_values

    @staticmethod
    def calculate_rsi(closes: List[float], period: int = 14) -> List[float]:
        """
        Calculates Relative Strength Index (RSI) using standard Wilder's smoothing.
        """
        if len(closes) < period + 1 or period <= 0:
            return []

        deltas = [closes[i] - closes[i - 1] for i in range(1, len(closes))]
        gains = [max(d, 0.0) for d in deltas]
        losses = [max(-d, 0.0) for d in deltas]

        # First average gain and loss
        avg_gain = sum(gains[:period]) / period
        avg_loss = sum(losses[:period]) / period

        rsi_list: List[float] = []
        if avg_loss == 0:
            rsi_list.append(100.0)
        else:
            rs = avg_gain / avg_loss
            rsi_list.append(100.0 - (100.0 / (1.0 + rs)))

        for i in range(period, len(deltas)):
            avg_gain = (avg_gain * (period - 1) + gains[i]) / period
            avg_loss = (avg_loss * (period - 1) + losses[i]) / period

            if avg_loss == 0:
                rsi_list.append(100.0)
            else:
                rs = avg_gain / avg_loss
                rsi_list.append(round(100.0 - (100.0 / (1.0 + rs)), 2))

        return rsi_list

    @staticmethod
    def calculate_macd(
        closes: List[float],
        fast: int = 12,
        slow: int = 26,
        signal: int = 9
    ) -> Dict[str, Any]:
        """
        Calculates MACD Line, Signal Line, and MACD Histogram.
        """
        if len(closes) < slow + signal:
            return {
                "macd_line": 0.0,
                "signal_line": 0.0,
                "histogram": 0.0,
                "prev_histogram": 0.0,
                "is_expanding": False,
            }

        ema_fast = SignalsDesk.calculate_ema(closes, fast)
        ema_slow = SignalsDesk.calculate_ema(closes, slow)

        # Align lengths of fast and slow EMAs to slow EMA length
        offset = len(ema_fast) - len(ema_slow)
        macd_series = [
            ema_fast[i + offset] - ema_slow[i] for i in range(len(ema_slow))
        ]

        if len(macd_series) < signal:
            return {
                "macd_line": 0.0,
                "signal_line": 0.0,
                "histogram": 0.0,
                "prev_histogram": 0.0,
                "is_expanding": False,
            }

        signal_series = SignalsDesk.calculate_ema(macd_series, signal)
        sig_offset = len(macd_series) - len(signal_series)

        histograms = [
            macd_series[i + sig_offset] - signal_series[i]
            for i in range(len(signal_series))
        ]

        curr_macd = round(macd_series[-1], 4)
        curr_sig = round(signal_series[-1], 4)
        curr_hist = round(histograms[-1], 4)
        prev_hist = round(histograms[-2], 4) if len(histograms) > 1 else curr_hist

        is_expanding = (curr_macd > curr_sig) and (curr_hist > 0) and (curr_hist >= prev_hist)

        return {
            "macd_line": curr_macd,
            "signal_line": curr_sig,
            "histogram": curr_hist,
            "prev_histogram": prev_hist,
            "is_expanding": is_expanding,
        }

    @staticmethod
    def calculate_bollinger_bands(
        closes: List[float],
        period: int = 20,
        num_std: float = 2.0
    ) -> Dict[str, float]:
        """
        Calculates 20-period Bollinger Bands (Upper, Middle/SMA, Lower, Bandwidth).
        """
        if len(closes) < period or period <= 0:
            return {"upper": 0.0, "middle": 0.0, "lower": 0.0, "bandwidth": 0.0}

        subset = closes[-period:]
        middle = sum(subset) / period
        variance = sum((x - middle) ** 2 for x in subset) / period
        std = math.sqrt(variance)

        upper = round(middle + (num_std * std), 2)
        lower = round(middle - (num_std * std), 2)
        bandwidth = round((upper - lower) / max(0.01, middle), 4)

        return {
            "upper": upper,
            "middle": round(middle, 2),
            "lower": lower,
            "bandwidth": bandwidth,
            "std": round(std, 2),
        }

    @staticmethod
    def calculate_rvol(volumes: List[float], lookback: int = 20) -> float:
        """
        Calculates Relative Volume (RVOL) = current volume / 20-day average volume.
        """
        if not volumes or len(volumes) < 2:
            return 1.0

        current_vol = volumes[-1]
        hist_vols = volumes[-lookback - 1:-1] if len(volumes) > lookback else volumes[:-1]

        if not hist_vols:
            return 1.0

        avg_vol = sum(hist_vols) / len(hist_vols)
        if avg_vol <= 0:
            return 1.0

        return round(current_vol / avg_vol, 2)

    @staticmethod
    def calculate_atr_14(
        highs: List[float],
        lows: List[float],
        closes: List[float],
        period: int = 14
    ) -> float:
        """Computes 14-period Average True Range (ATR)."""
        if len(closes) < 2 or len(highs) < len(closes) or len(lows) < len(closes):
            return round(closes[-1] * 0.02, 2) if closes else 1.0

        tr_values: List[float] = []
        for i in range(1, len(closes)):
            h = highs[i]
            l = lows[i]
            prev_c = closes[i - 1]
            tr = max(h - l, abs(h - prev_c), abs(l - prev_c))
            tr_values.append(tr)

        if not tr_values:
            return round(closes[-1] * 0.02, 2)

        subset = tr_values[-period:] if len(tr_values) >= period else tr_values
        return round(sum(subset) / len(subset), 2)

    # -------------------------------------------------------------------------
    # Strategy 1: Breakout Momentum
    # -------------------------------------------------------------------------

    def evaluate_breakout_momentum(
        self,
        symbol: str,
        closes: List[float],
        highs: Optional[List[float]] = None,
        lows: Optional[List[float]] = None,
        volumes: Optional[List[float]] = None,
        current_price: Optional[float] = None
    ) -> Optional[SignalCandidate]:
        """
        Strategy 1: Breakout Momentum
        Setup Criteria:
        1. 20-day high channel breakout: Current price >= 20-day high channel.
        2. RVOL >= 1.3x: Substantial volume surge confirming breakout.
        3. MACD Expansion: MACD line > Signal line with expanding positive histogram.
        """
        if len(closes) < 21:
            return None

        price = current_price if current_price is not None else closes[-1]
        h_series = highs if (highs and len(highs) >= len(closes)) else closes
        l_series = lows if (lows and len(lows) >= len(closes)) else closes
        v_series = volumes if (volumes and len(volumes) >= len(closes)) else [1000.0] * len(closes)

        # 1. 20-day high channel calculation (excluding today's bar)
        channel_high_20 = max(h_series[-21:-1])
        is_breakout = price >= channel_high_20

        # 2. RVOL
        rvol = self.calculate_rvol(v_series, lookback=self.MOMENTUM_CHANNEL_DAYS)
        rvol_passed = rvol >= self.MOMENTUM_RVOL_MIN

        # 3. MACD Expansion
        macd_data = self.calculate_macd(closes)
        macd_passed = macd_data["is_expanding"]

        if is_breakout and rvol_passed and macd_passed:
            atr = self.calculate_atr_14(h_series, l_series, closes)
            stop_loss = round(max(0.01, price - (2.0 * atr)), 2)
            # Ensure target offers at least 2.0 R:R
            risk = max(0.01, price - stop_loss)
            target_price = round(price + max(4.0 * atr, risk * self.MIN_RR_RATIO), 2)
            rr_ratio = round((target_price - price) / risk, 2)

            return SignalCandidate(
                symbol=symbol,
                strategy_name="Breakout Momentum",
                entry_price=round(price, 2),
                stop_loss=stop_loss,
                target_price=target_price,
                rr_ratio=rr_ratio,
                metrics={
                    "channel_high_20": round(channel_high_20, 2),
                    "rvol": rvol,
                    "macd_line": macd_data["macd_line"],
                    "signal_line": macd_data["signal_line"],
                    "macd_hist": macd_data["histogram"],
                    "atr_14": atr,
                },
                notes="20-day high channel breakout with volume expansion and bullish MACD spread."
            )

        return None

    # -------------------------------------------------------------------------
    # Strategy 2: Mean-Reversion Dips
    # -------------------------------------------------------------------------

    def evaluate_mean_reversion_dip(
        self,
        symbol: str,
        closes: List[float],
        roic: float,
        highs: Optional[List[float]] = None,
        lows: Optional[List[float]] = None,
        volumes: Optional[List[float]] = None,
        current_price: Optional[float] = None
    ) -> Optional[SignalCandidate]:
        """
        Strategy 2: Mean-Reversion Dips
        Setup Criteria:
        1. High-ROIC quality franchise: ROIC >= 12% (0.12).
        2. Pullback zone: Price within 3.0% of 50 EMA, 200 EMA, or Lower Bollinger Band.
        3. RSI inflection: 14-period RSI <= 38.0 and turning upward (RSI_t > RSI_{t-1}).
        """
        if len(closes) < 35:
            return None

        # 1. Quality hurdle check
        if roic < self.DIP_ROIC_MIN:
            return None

        price = current_price if current_price is not None else closes[-1]
        h_series = highs if (highs and len(highs) >= len(closes)) else closes
        l_series = lows if (lows and len(lows) >= len(closes)) else closes

        # 2. Moving averages and Bollinger Bands
        ema_50_series = self.calculate_ema(closes, 50) if len(closes) >= 50 else []
        ema_200_series = self.calculate_ema(closes, 200) if len(closes) >= 200 else []
        bb = self.calculate_bollinger_bands(closes, period=20, num_std=2.0)

        ema_50 = ema_50_series[-1] if ema_50_series else None
        ema_200 = ema_200_series[-1] if ema_200_series else None
        lower_bb = bb["lower"]

        # Near support tests (within 3.0% of EMA 50, EMA 200, or at/below Lower BB)
        near_50 = (ema_50 is not None) and (abs(price - ema_50) / ema_50 <= 0.035)
        near_200 = (ema_200 is not None) and (abs(price - ema_200) / ema_200 <= 0.035)
        near_lower_bb = (lower_bb > 0) and (price <= lower_bb * 1.025)

        support_test = near_50 or near_200 or near_lower_bb
        if not support_test:
            return None

        # 3. RSI <= 38 turning up
        rsi_series = self.calculate_rsi(closes, period=14)
        if len(rsi_series) < 2:
            return None

        curr_rsi = rsi_series[-1]
        prev_rsi = rsi_series[-2]
        rsi_oversold_turning_up = (curr_rsi <= self.DIP_RSI_MAX) and (curr_rsi > prev_rsi)

        if rsi_oversold_turning_up:
            atr = self.calculate_atr_14(h_series, l_series, closes)
            # Stop just below the lowest support level or 1.5x ATR
            support_ref = lower_bb if (near_lower_bb and lower_bb > 0) else (ema_50 or ema_200 or price * 0.95)
            stop_loss = round(min(support_ref * 0.98, price - (1.5 * atr)), 2)
            risk = max(0.01, price - stop_loss)
            target_price = round(price + max(3.0 * atr, risk * self.MIN_RR_RATIO), 2)
            rr_ratio = round((target_price - price) / risk, 2)

            support_desc = (
                "Lower BB" if near_lower_bb else
                "50 EMA" if near_50 else "200 EMA"
            )

            return SignalCandidate(
                symbol=symbol,
                strategy_name="Mean-Reversion Dip",
                entry_price=round(price, 2),
                stop_loss=stop_loss,
                target_price=target_price,
                rr_ratio=rr_ratio,
                metrics={
                    "roic": round(roic, 4),
                    "rsi": curr_rsi,
                    "prev_rsi": prev_rsi,
                    "support_zone": support_desc,
                    "lower_bb": lower_bb,
                    "ema_50": round(ema_50, 2) if ema_50 else None,
                    "ema_200": round(ema_200, 2) if ema_200 else None,
                    "atr_14": atr,
                },
                notes=f"High-ROIC ({roic*100:.1f}%) pullback to {support_desc} with RSI hook ({curr_rsi:.1f} > {prev_rsi:.1f})."
            )

        return None

    # -------------------------------------------------------------------------
    # Strategy 3: Multi-Factor Composite Swings
    # -------------------------------------------------------------------------

    def evaluate_composite_swing(
        self,
        symbol: str,
        closes: List[float],
        highs: Optional[List[float]] = None,
        lows: Optional[List[float]] = None,
        volumes: Optional[List[float]] = None,
        current_price: Optional[float] = None
    ) -> Optional[SignalCandidate]:
        """
        Strategy 3: Multi-Factor Composite Swings
        Setup Criteria:
        1. Trend Alignment: Price >= EMA 50 and (EMA 50 > EMA 200 or upward structure).
        2. RVOL: RVOL >= 1.1x healthy institutional participation.
        3. RSI: 40.0 <= RSI <= 68.0 sweet-spot momentum.
        4. ATR Stop with R:R >= 2.0:1.
        """
        if len(closes) < 50:
            return None

        price = current_price if current_price is not None else closes[-1]
        h_series = highs if (highs and len(highs) >= len(closes)) else closes
        l_series = lows if (lows and len(lows) >= len(closes)) else closes
        v_series = volumes if (volumes and len(volumes) >= len(closes)) else [1000.0] * len(closes)

        # 1. Trend Alignment
        ema_50_series = self.calculate_ema(closes, 50)
        if not ema_50_series:
            return None
        ema_50 = ema_50_series[-1]

        # 200 EMA check if available, otherwise 20 EMA > 50 EMA
        ema_200_series = self.calculate_ema(closes, 200) if len(closes) >= 200 else []
        if ema_200_series:
            trend_aligned = (price >= ema_50 * 0.985) and (ema_50 >= ema_200_series[-1] * 0.985)
        else:
            ema_20_series = self.calculate_ema(closes, 20)
            trend_aligned = (price >= ema_50 * 0.985) and (ema_20_series[-1] >= ema_50 * 0.985)

        if not trend_aligned:
            return None

        # 2. RVOL
        rvol = self.calculate_rvol(v_series, lookback=20)
        if rvol < self.COMPOSITE_RVOL_MIN:
            return None

        # 3. RSI Sweet Spot
        rsi_series = self.calculate_rsi(closes, period=14)
        if not rsi_series:
            return None
        curr_rsi = rsi_series[-1]
        if not (self.COMPOSITE_RSI_MIN <= curr_rsi <= self.COMPOSITE_RSI_MAX):
            return None

        # 4. ATR Stop and Target with R:R >= 2.0:1
        atr = self.calculate_atr_14(h_series, l_series, closes)
        stop_loss = round(max(0.01, price - (2.0 * atr)), 2)
        risk = max(0.01, price - stop_loss)
        target_price = round(price + (risk * self.MIN_RR_RATIO), 2)
        rr_ratio = round((target_price - price) / risk, 2)

        if rr_ratio >= self.MIN_RR_RATIO:
            return SignalCandidate(
                symbol=symbol,
                strategy_name="Multi-Factor Composite Swing",
                entry_price=round(price, 2),
                stop_loss=stop_loss,
                target_price=target_price,
                rr_ratio=rr_ratio,
                metrics={
                    "rvol": rvol,
                    "rsi": curr_rsi,
                    "ema_50": round(ema_50, 2),
                    "atr_14": atr,
                    "trend_aligned": True,
                },
                notes="Trend aligned with RVOL participation and optimal 40-68 RSI momentum sweet spot."
            )

        return None

    # -------------------------------------------------------------------------
    # Comprehensive Symbol & Universe Scanning
    # -------------------------------------------------------------------------

    def set_cached_history(
        self,
        symbol: str,
        closes: List[float],
        highs: Optional[List[float]] = None,
        lows: Optional[List[float]] = None,
        volumes: Optional[List[float]] = None,
        roic: float = 0.15
    ) -> None:
        """Injects or caches synthetic/historical data for testing or offline evaluation."""
        self._history_cache[symbol] = {
            "closes": closes,
            "highs": highs or closes,
            "lows": lows or closes,
            "volumes": volumes or [1000.0] * len(closes),
            "roic": [roic],
        }

    def scan_symbol(self, symbol: str) -> List[SignalCandidate]:
        """
        Evaluates a single symbol across all three swing strategies.
        """
        candidates: List[SignalCandidate] = []

        # Check in-memory cache first
        if symbol in self._history_cache:
            data = self._history_cache[symbol]
            closes = data["closes"]
            highs = data["highs"]
            lows = data["lows"]
            volumes = data["volumes"]
            roic = data["roic"][0] if data["roic"] else 0.15

            # 1. Breakout Momentum
            sig1 = self.evaluate_breakout_momentum(symbol, closes, highs, lows, volumes)
            if sig1:
                candidates.append(sig1)

            # 2. Mean-Reversion Dip
            sig2 = self.evaluate_mean_reversion_dip(symbol, closes, roic, highs, lows, volumes)
            if sig2:
                candidates.append(sig2)

            # 3. Composite Swing
            sig3 = self.evaluate_composite_swing(symbol, closes, highs, lows, volumes)
            if sig3:
                candidates.append(sig3)

            return candidates

        # If feed is available, attempt fundamentals/quotes
        roic_val = 0.15
        if self.feed:
            fin = self.feed.get_financials(symbol)
            if fin and "roic" in fin:
                roic_val = float(fin["roic"])

        return candidates

    def scan_signals(self, symbols: Optional[List[str]] = None) -> List[SignalCandidate]:
        """
        Scans a candidate universe across all 3 mathematical strategies.
        """
        if symbols is None:
            symbols = list(self._history_cache.keys())
            if not symbols and self.state_mgr:
                symbols = [h.symbol for h in self.state_mgr.get_all_active_holdings()]
                symbols.extend([w.symbol for w in self.state_mgr.state.watchlist])
                symbols = list(set(symbols))

        all_candidates: List[SignalCandidate] = []
        for sym in symbols:
            try:
                results = self.scan_symbol(sym)
                all_candidates.extend(results)
            except Exception as e:
                logger.warning(f"Error scanning symbol {sym}: {e}")

        return all_candidates

    # -------------------------------------------------------------------------
    # Formatted Card Generator for Telegram /signals
    # -------------------------------------------------------------------------

    def format_signals_card(self, candidates: Optional[List[SignalCandidate]] = None) -> str:
        """
        Generates an institutional Telegram Markdown summary card for `/signals`.
        """
        if candidates is None:
            candidates = self.scan_signals()

        if not candidates:
            return (
                "📡 **SIGNALS DESK — 3-STRATEGY SWING SCANNER**\n\n"
                "• **Status:** Active Scanning\n"
                "• **Qualified Setups:** None currently meeting strict mathematical hurdles.\n\n"
                "_Filters Active: Breakout Momentum (20-Day High, RVOL >= 1.3x, MACD expansion) | "
                "Mean-Reversion Dips (ROIC >= 12%, RSI <= 38 turning up) | "
                "Composite Swings (Trend aligned, R:R >= 2.0:1)._"
            )

        lines = [
            "📡 **SIGNALS DESK — QUANTITATIVE SWING SELECTIONS**",
            f"_Identified {len(candidates)} qualified setup(s) meeting mathematical execution rules._\n"
        ]

        for i, c in enumerate(candidates, 1):
            strat_icon = "🚀" if "Breakout" in c.strategy_name else ("🔄" if "Mean-Reversion" in c.strategy_name else "📈")
            lines.append(f"{strat_icon} **#{i} {c.symbol}** — `{c.strategy_name}`")
            lines.append(f"   • **Entry:** `{c.entry_price:.2f}` | **Stop:** `{c.stop_loss:.2f}` | **Target:** `{c.target_price:.2f}`")
            lines.append(f"   • **Risk/Reward:** `{c.rr_ratio:.2f}:1`")

            metric_str = ", ".join(f"{k}: {v}" for k, v in list(c.metrics.items())[:4])
            lines.append(f"   • **Metrics:** `{metric_str}`")
            if c.notes:
                lines.append(f"   • _Context:_ {c.notes}")
            lines.append("")

        return "\n".join(lines).strip()
